'use strict';

// Prints the schema so a DBA can run it by hand:  npm run schema:oracle
const { schemaStatements } = require('./schema');

const dialect = process.argv[2] || 'oracle';
process.stdout.write(`-- ZipGo schema (${dialect}). Generated by src/db/print-schema.js\n\n`);
for (const sql of schemaStatements(dialect, { includeUpgrades: false })) {
  process.stdout.write(`${sql.replace(/\n {4}/g, '\n  ').replace(/\n {2}\)$/, '\n)')};\n\n`);
}
